struct DspGraphCursors
{
    // P:0x1c9 sets r3/r4 to X/Y:0x5f. The mixer prefix consumes one word
    // before P:0x1df, so the oscillator begins with both cursors at 0x60.
    std::uint16_t r3AtSampleGraph = 0x60;
    std::uint16_t r4AtSampleGraph = 0x60;
    std::uint16_t n2 = 0x7bc;
    std::uint16_t n5 = 0x780;
    std::uint16_t r6 = 0x620;
    bool n2n5Captured = true;
};

